// Runs the bot (headless careful + reckless, browser careful) and writes the playtest report.
// Usage: node bot/write-report.mjs [out=docs/reviews/S1-bot-report.md] [headlessRuns=30] [browserRuns=5]
import { writeFileSync } from "node:fs";
import { runOne } from "./run-headless.mjs";
import { runBrowser } from "./run-browser.mjs";
import { summarise, table } from "./report.js";

const out = process.argv[2] ?? "docs/reviews/S1-bot-report.md", nH = Number(process.argv[3] ?? 30), nB = Number(process.argv[4] ?? 5);
const head = (profile) => Array.from({ length: nH }, (_, i) => runOne(i + 1, 20000, profile));
const careful = head({}), reckless = head({ reckless: true });
const browser = await runBrowser(nB, 12000, {});
const row = (name, s) => `| ${name} | ${s.runs} | ${s.cleared} | ${s.died} | ${s.timeout} | ${s.kills}/${s.monsters} | ${s.ttkMeanSec} s | ${s.ttkMaxSec} s | ${s.stuckEvents} | ${s.meanRunSec} s |`;
const sums = { careful: summarise(careful), reckless: summarise(reckless), browser: summarise(browser.runs) };
const md = `# S1 bot playtest report

Generated by \`node bot/write-report.mjs\` (bot policy: \`bot/policy.js\`, shared by both runners). Date: 2026-10-13.

The bot explores the floor room by room, fights what it meets and stops when the floor is clear or the hero is dead.
Time-to-kill (TTK) is measured from the first damage dealt to a monster to its death. A *stuck event* is an active order
(walk or chase) with neither movement nor a swing for ${"150"} ticks (2.5 s; 300 ticks while chasing a target).

| Run set | Runs | Cleared | Died | Timeout | Kills | TTK mean | TTK max | Stuck events | Mean run |
|---|---|---|---|---|---|---|---|---|---|
${row("Headless, careful (waits for chasers), seeds 1-" + nH, sums.careful)}
${row("Headless, reckless (walks into packs), seeds 1-" + nH, sums.reckless)}
${row("Browser via window.__app (Playwright), seeds 1-" + nB, sums.browser)}

Browser run: ${browser.errors.length} page errors or console errors over ${nB} full runs.

## Findings

1. **Mutual-pursuit orbit (fixed in the core, \`systems/intent.js\`, \`config.holdRadius\`).** A hero chasing a monster that is already chasing the hero
   (the faster Printer Imp) planned to the monster's old tile while the monster planned to the hero's old tile: both circled a prop cluster or a
   corridor ring for ever (run timed out with half the monsters alive). The hero now waits once a chasing target is within 2 tiles of where it stands.
   Seeds 4 and 5 went from timeout to cleared. Unit test: \`test/bot.test.js\` ("S1 hardening").
2. **Residual orbit at 3+ tiles (open, follow-up).** A hero that deliberately chases a faster chaser around a prop cluster can still orbit (the reckless
   profile times out on one seed in ${nH}). The careful bot avoids it by waiting for chasers. Fix options: predictive intercept (path to the target's next tile) or monsters
   pathing to the hero's \`next\` tile; both change the golden replay, so they need their own slice and a new golden.
3. **Dithering between two targets (bot bug, fixed in the policy).** Two monsters at similar range made the bot re-target every decision; hysteresis added, and a
   monster that is already hitting the hero counts as 2 tiles closer. With this the first zero-kill deaths (hero standing next to the wrong monster while another hit it) are gone.
4. **Difficulty (not changed, design call).** The reckless bot dies on about ${Math.round((sums.reckless.died / sums.reckless.runs) * 100)}% of floors, always to a pack of 3-4 met in the open at level 1; waiting in a corridor
   for chasers clears ${sums.careful.cleared}/${sums.careful.runs}. The hero has no escape or healing in S1 (potions and skills arrive in S2), so the numbers are a baseline for the S2 balance pass.
5. **No stuck events** remain in the careful profile (${sums.careful.stuckEvents}); path planning never refused a bot move (${sums.careful.failedMoves} refused). The bot gave up waiting for a chaser ${sums.careful.waitGaveUp} times (blocked monsters).

## Per-seed results

### Headless, careful
${table(careful)}

### Headless, reckless
${table(reckless)}

### Browser
${table(browser.runs)}
`;
writeFileSync(out, md);
console.log(`wrote ${out}`);
console.log(JSON.stringify(sums));
